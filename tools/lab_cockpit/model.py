def _pipeline_sha_by_filename(run_dir: Path) -> dict[str, str]:
    """basename -> sha256 from the committed artifact index (display only).

    The cockpit never re-verifies these hashes; it surfaces the pipeline's own
    manifest so the operator can cross-check an artifact by hash where present.
    """
    index = _read_json(run_dir / "artifact_index.json") or {}
    shas: dict[str, str] = {}
    for entry in (index.get("artifacts") or {}).values():
        path = entry.get("path")
        sha = entry.get("sha256")
        if isinstance(path, str) and isinstance(sha, str):
            shas[Path(path).name] = sha
    return shas


def _pipeline_run_artifacts(
    run_dir: Path, runs_root: str, run_id: str
) -> list[dict[str, Any]]:
    """Repo-relative artifact drilldown for one run (present/missing + sha).

    Paths are reconstructed repo-relative from the run directory; the absolute
    paths embedded by the orchestrator are never surfaced.
    """
    shas = _pipeline_sha_by_filename(run_dir)
    artifacts: list[dict[str, Any]] = []
    for key, filename in _PIPELINE_ARTIFACT_FILES:
        present = (run_dir / filename).exists()
        artifacts.append(
            {
                "key": key,
                "filename": filename,
                "path": f"{runs_root}/{run_id}/{filename}",
                "present": present,
                "sha256": shas.get(filename) if present else None,
            }
        )
    return artifacts


def _pipeline_run_view(run_dir: Path, runs_root: str) -> dict[str, Any]:
    """Project one committed pipeline run packet into a read-only run card.

    Fails closed: a missing or malformed ``pipeline_state.json`` yields an
    explicit invalid card rather than a fabricated run.
    """
    run_id = run_dir.name
    state = _read_json(run_dir / "pipeline_state.json")
    if not state:
        return {
            "pipeline_run_id": run_id,
            "available": False,
            "display_status": "blocked_or_invalid",
            "display_label": "MALFORMED / UNAVAILABLE",
            "invalid_reason": "pipeline_state.json missing or malformed",
            "current_stage": None,
            "runner_invoked": None,
            "spine_only": False,
            "awaiting_approval": False,
            "blocked_reasons": [],
            "stages": [],
            "approval": {"required": False},
            "artifacts": _pipeline_run_artifacts(run_dir, runs_root, run_id),
        }

    raw_status = state.get("pipeline_status")
    display_status, display_label = _PIPELINE_DISPLAY_STATUS.get(
        raw_status, ("blocked_or_invalid", "UNKNOWN / INVALID")
    )

    execution = _read_json(run_dir / "noncanonical_execution_summary.json")
    runner_invoked: bool | None = None
    execution_kind: str | None = None
    if execution:
        runner_invoked = bool(execution.get("runner_invoked", False))
        execution_kind = execution.get("execution_kind")

    # An approved completion is spine-only when the runner was not invoked. Label
    # it honestly; never present the deterministic spine proof as a real run.
    spine_only = raw_status == "complete" and runner_invoked is False
    if spine_only:
        display_status = "complete_spine_only"
        display_label = "COMPLETE · SPINE ONLY"

    approval_req = _read_json(run_dir / "approval_requirement.json") or {}
    awaiting = raw_status == "awaiting_prereg_approval"
    stages = [
        {
            "stage": s.get("stage"),
            "status": s.get("status"),
            "detail": s.get("detail"),
            "blocked_reasons": list(s.get("blocked_reasons") or []),
        }
        for s in (state.get("stage_statuses") or [])
    ]
    return {
        "pipeline_run_id": run_id,
        "available": True,
        "request_id": state.get("request_id"),
        "source_idea": state.get("source_idea"),
        "symbol": state.get("symbol"),
        "timeframe": state.get("timeframe"),
        "requested_by": state.get("requested_by"),
        "raw_status": raw_status,
        "display_status": display_status,
        "display_label": display_label,
        "current_stage": state.get("current_stage"),
        "runner_invoked": runner_invoked,
        "execution_kind": execution_kind,
        "spine_only": spine_only,
        "awaiting_approval": awaiting,
        "blocked_reasons": list(state.get("blocked_reasons") or []),
        "approval": {
            "required": bool(approval_req),
            "approval_scope": (approval_req.get("required_fields") or {}).get(
                "approval_scope"
            ),
            "preregistration_packet_sha256": approval_req.get(
                "preregistration_packet_sha256"
            ),
            "awaiting": awaiting,
        },
        "stages": stages,
        "non_authority_flags": state.get("non_authority_flags") or {},
        "artifacts": _pipeline_run_artifacts(run_dir, runs_root, run_id),
    }


def build_pipeline_state(
    repo_root: Path = REPO_ROOT, runs_root: str = PIPELINE_RUNS_ROOT
) -> dict[str, Any]:
    """Read-only projection of committed lab-pipeline run packets.

    Deterministic: runs are ordered by run id. Fails closed to ``unavailable``
    when no committed run packets are present.
    """
    empty_totals = {
        "run_count": 0,
        "awaiting_approval": 0,
        "blocked_or_invalid": 0,
        "complete_spine_only": 0,
        "complete_real": 0,
    }
    runs_dir = repo_root / runs_root
    if not runs_dir.is_dir():
        return {
            "available": False,
            "status": "unavailable",
            "runs_root": runs_root,
            "spine_only": False,
            "spine_only_label": PIPELINE_SPINE_ONLY_LABEL,
            "unavailable_reason": "no committed pipeline run packets found",
            "totals": dict(empty_totals),
            "runs": [],
        }

    run_dirs = sorted(
        (
            d
            for d in runs_dir.iterdir()
            if d.is_dir()
            and any((d / filename).exists() for _, filename in _PIPELINE_ARTIFACT_FILES)
        ),
        key=lambda d: d.name,
    )
    if not run_dirs:
        return {
            "available": False,
            "status": "unavailable",
            "runs_root": runs_root,
            "spine_only": False,
            "spine_only_label": PIPELINE_SPINE_ONLY_LABEL,
            "unavailable_reason": "pipeline runs directory present but empty",
            "totals": dict(empty_totals),
            "runs": [],
        }

    runs = [_pipeline_run_view(d, runs_root) for d in run_dirs]
    totals = {
        "run_count": len(runs),
        "awaiting_approval": sum(
            1 for r in runs if r["display_status"] == "awaiting_prereg_approval"
        ),
        "blocked_or_invalid": sum(
            1 for r in runs if r["display_status"] == "blocked_or_invalid"
        ),
        "complete_spine_only": sum(
            1 for r in runs if r["display_status"] == "complete_spine_only"
        ),
        "complete_real": sum(1 for r in runs if r["display_status"] == "complete"),
    }
    # Spine-only overall while no run ever invoked a real runner. The honest
    # label is surfaced whenever a completion exists but all are spine proofs.
    any_real_runner = any(r.get("runner_invoked") is True for r in runs)
    return {
        "available": True,
        "status": "present",
        "runs_root": runs_root,
        "spine_only": not any_real_runner,
        "spine_only_label": PIPELINE_SPINE_ONLY_LABEL,
        "totals": totals,
        "runs": runs,
    }


