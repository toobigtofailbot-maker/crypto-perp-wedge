    terminal_state = index.get("terminal_state")
    if adapter_status != "completed":
        display_state = "blocked_or_failed"
        display_label = "BLOCKED / FAILED"
    else:
        display_state = terminal_state or "advisory_packet_ready"
        display_label = index.get("terminal_label") or "ADVISORY PACKET READY"

    advisory = _read_json(run_dir / "advisory_review_packet.json") or {}
    reached = {
        s.get("stage")
        for s in (index.get("stage_ladder") or [])
        if s.get("reached")
    }
    return {
        "run_id": run_id,
        "available": True,
        "real_run": bool(index.get("real_run", False)),
        "runner_invoked": bool(index.get("runner_invoked", False)),
        "display_state": display_state,
        "display_label": display_label,
        "adapter_status": adapter_status,
        "posture": index.get("posture"),
        "provenance": dict(index.get("provenance") or {}),
        "stage_ladder": [
            {
                "stage": s.get("stage"),
                "label": s.get("label"),
                "reached": bool(s.get("reached")),
            }
            for s in (index.get("stage_ladder") or [])
        ],
        "reached_states": sorted(reached),
        "denominator_counts": {
            status: (index.get("denominator_counts") or {}).get(status, 0)
            for status in PRODUCT_DENOMINATOR_STATUSES
        },
        "full_denominator_preserved": bool(
            index.get("full_denominator_preserved", False)
        ),
        # Advisory-only surface routing: a review value, never a candidate admission.
        "candidate_surface_status": index.get("candidate_surface_status"),
        "candidate_surface_allowed_statuses": list(
            index.get("candidate_surface_allowed_statuses") or []
        ),
        "candidate_lifecycle_written": bool(
            index.get("candidate_lifecycle_written", False)
        ),
        "go_auto_admission": bool(index.get("go_auto_admission", False)),
        "go_auto_crossing": bool(index.get("go_auto_crossing", False)),
        "go_auto_promotion": bool(index.get("go_auto_promotion", False)),
        "non_promotion_posture": dict(index.get("non_promotion_posture") or {}),
        "withheld_statistics": _product_withheld_view(advisory),
        "robustness": _product_robustness_view(advisory),
        "candidate_review": _product_candidate_review_view(advisory),
        "artifacts": [
            {
                "filename": a.get("filename"),
                "path": a.get("path"),
                "present": bool(
                    (repo_root / a.get("path", "")).exists() if a.get("path") else False
                ),
                "sha256": a.get("sha256"),
            }
            for a in (index.get("artifacts") or [])
        ],
    }


