def _read_json(path: Path) -> dict[str, Any] | None:
    """Read a committed JSON artifact, failing closed to ``None``."""
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


